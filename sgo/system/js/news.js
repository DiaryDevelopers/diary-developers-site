function createNewsCards(newsArray) {
    newsArray.forEach(newsItem => {
        const newsCard = document.createElement('li');
        newsCard.className = 'news-card';

        const title = document.createElement('div');
        title.className = 'news-title h1';
        title.textContent = newsItem.title;

        const content = document.createElement('div');
        content.className = 'news-content';
        content.textContent = newsItem.content;

        const date = document.createElement('div');
        date.className = 'news-date';
        date.textContent = newsItem.date;

        newsCard.appendChild(title);
        newsCard.appendChild(content);
        newsCard.appendChild(date);

        document.querySelector('.news-cards').appendChild(newsCard);
    });
}

